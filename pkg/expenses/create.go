// CreateRequest is the POST body: a full Expense with the client's ID
// (spec "Expense API contract", Create). The server sets the timestamps,
// Currency and Status.
//
// Ticket 06 adds driveFileId, fileHash and force; unknown fields are
// ignored so an older or newer client never fails to decode.
type CreateRequest struct {
	ID          string `json:"id"`
	ExpenseDate string `json:"expenseDate"`
	LoggedBy    string `json:"loggedBy"`
	// PaidBy defaults to LoggedBy when blank.
	PaidBy        string   `json:"paidBy"`
	Amount        *float64 `json:"amount"`
	Category      string   `json:"category"`
	MerchantNote  string   `json:"merchantNote"`
	PaymentMethod string   `json:"paymentMethod"`
	// ReimbursementStatus defaults to none; the Quick Expense "I paid from
	// my own pocket" toggle sends pending.
	ReimbursementStatus string `json:"reimbursementStatus"`
}

// MaxAmount is one crore rupees, the largest Expense the spec allows.
const MaxAmount = 1_00_00_000

// MaxNoteLength caps Merchant_Note, in characters.
const MaxNoteLength = 500

// ValidationError is a request the Ledger must not take; Code is the
// machine-readable reason the client can switch on.
type ValidationError struct {
	Code    string
	Message string
}

func (e *ValidationError) Error() string { return e.Message }

func invalid(code, format string, args ...any) *ValidationError {
	return &ValidationError{Code: code, Message: fmt.Sprintf(format, args...)}
}

var uuidPattern = regexp.MustCompile(`^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$`)

// Validate checks a create against the Household's Members and Categories
// at time now, and returns the Expense to append: timestamps in IST,
// Currency INR, Status active, names in the Ledger's own spelling.
func Validate(req CreateRequest, members []ledger.Member, categories []ledger.Category, now time.Time) (ledger.Expense, *ValidationError) {
	id := strings.ToLower(strings.TrimSpace(req.ID))
	if !uuidPattern.MatchString(id) {
		return ledger.Expense{}, invalid("INVALID_ID", "The Expense ID must be a UUID generated by the app")
	}
	if req.Amount == nil {
		return ledger.Expense{}, invalid("INVALID_AMOUNT", "The amount is missing")
	}
	amount := *req.Amount
	if amount <= 0 || amount > MaxAmount || math.IsNaN(amount) {
		return ledger.Expense{}, invalid("INVALID_AMOUNT", "The amount must be more than ₹0 and at most ₹1,00,00,000")
	}
	if paise := amount * 100; math.Abs(paise-math.Round(paise)) > 1e-6 {
		return ledger.Expense{}, invalid("INVALID_AMOUNT", "The amount can have at most two decimals")
	}
	category, ok := findCategory(categories, req.Category)
	if !ok {
		return ledger.Expense{}, invalid("UNKNOWN_CATEGORY", "%q is not a Category in the Ledger", req.Category)
	}
	method, ok := paymentMethod(req.PaymentMethod)
	if !ok {
		return ledger.Expense{}, invalid("INVALID_PAYMENT_METHOD", "The Payment Method must be UPI, Cash, Card or Bank Transfer")
	}
	date, err := time.ParseInLocation(ledger.DateLayout, strings.TrimSpace(req.ExpenseDate), ledger.IST)
	if err != nil {
		return ledger.Expense{}, invalid("INVALID_DATE", "The date must be YYYY-MM-DD")
	}
	today := now.In(ledger.IST)
	tomorrow := time.Date(today.Year(), today.Month(), today.Day()+1, 0, 0, 0, 0, ledger.IST)
	if date.After(tomorrow) {
		return ledger.Expense{}, invalid("INVALID_DATE", "The date can be at most one day ahead")
	}
	loggedBy, ok := findMember(members, req.LoggedBy)
	if !ok {
		return ledger.Expense{}, invalid("UNKNOWN_MEMBER", "Logged By %q is not a Member in the Ledger", req.LoggedBy)
	}
	paidBy := loggedBy
	if strings.TrimSpace(req.PaidBy) != "" {
		if paidBy, ok = findMember(members, req.PaidBy); !ok {
			return ledger.Expense{}, invalid("UNKNOWN_MEMBER", "Paid By %q is not a Member in the Ledger", req.PaidBy)
		}
	}
	reimbursement := ledger.ReimbursementNone
	switch r := ledger.Reimbursement(strings.TrimSpace(req.ReimbursementStatus)); r {
	case "", ledger.ReimbursementNone:
	case ledger.ReimbursementPending, ledger.ReimbursementDone:
		reimbursement = r
	default:
		return ledger.Expense{}, invalid("INVALID_REIMBURSEMENT", "Reimbursement must be none, pending or done")
	}
	note := strings.TrimSpace(req.MerchantNote)
	if utf8.RuneCountInString(note) > MaxNoteLength {
		return ledger.Expense{}, invalid("INVALID_NOTE", "The note can be at most %d characters", MaxNoteLength)
	}
	stamp := now.In(ledger.IST).Format(time.RFC3339)
	return ledger.Expense{
		ID: id, CreatedAt: stamp, UpdatedAt: stamp, ExpenseDate: date.Format(ledger.DateLayout),
		LoggedBy: loggedBy, PaidBy: paidBy, Amount: amount, Currency: ledger.Currency,
		Category: category, MerchantNote: note, PaymentMethod: method,
		Reimbursement: reimbursement, Status: ledger.StatusActive,
	}, nil
}

// findCategory matches a name the way a human would (case and surrounding
// spaces ignored) and returns the Ledger's spelling.
func findCategory(categories []ledger.Category, name string) (string, bool) {
	name = strings.TrimSpace(name)
	for _, c := range categories {
		if name != "" && strings.EqualFold(c.Name, name) {
			return c.Name, true
		}
	}
	return "", false
}

func findMember(members []ledger.Member, id string) (string, bool) {
	id = strings.TrimSpace(id)
	for _, m := range members {
		if id != "" && m.MemberID == id {
			return m.MemberID, true
		}
	}
	return "", false
}

func paymentMethod(s string) (ledger.PaymentMethod, bool) {
	for _, pm := range ledger.PaymentMethods {
		if string(pm) == s {
			return pm, true
		}
	}
	return "", false
}

// maxBody bounds the POST body; an Expense is a few hundred bytes.
const maxBody = 64 << 10

func (s Service) create(w http.ResponseWriter, r *http.Request) {
	var req CreateRequest
	if err := json.NewDecoder(http.MaxBytesReader(w, r.Body, maxBody)).Decode(&req); err != nil {
		httpjson.WriteError(w, http.StatusBadRequest, "BAD_REQUEST", "The body must be a JSON Expense")
		return
	}
	snap, err := s.Ledger.Read(r.Context(), ledger.Expenses, ledger.Members, ledger.Categories)
	if err != nil {
		writeLedgerError(w, err)
		return
	}
	// Idempotent replay first: a create the client retried after a lost
	// response is answered with what was stored, whatever it sends now.
	if stored, _, ok := ledger.FindExpense(snap.Rows[ledger.Expenses], strings.ToLower(req.ID)); ok {
		httpjson.Write(w, http.StatusOK, viewOf(stored))
		return
	}
	expense, verr := Validate(req, ledger.ParseMembers(snap.Rows[ledger.Members]), ledger.ParseCategories(snap.Rows[ledger.Categories]), s.now())
	if verr != nil {
		httpjson.WriteError(w, http.StatusUnprocessableEntity, verr.Code, verr.Message)
		return
	}
	if err := s.Ledger.Append(r.Context(), ledger.Expenses, [][]string{expense.Row()}); err != nil {
		writeLedgerError(w, err)
		return
	}
	httpjson.Write(w, http.StatusCreated, viewOf(expense))
}

// writeLedgerError maps a Ledger failure onto the envelope: a missing
// Ledger asks for Bootstrap, anything else is Google's fault.
func writeLedgerError(w http.ResponseWriter, err error) {
	if errors.Is(err, ledger.ErrNotFound) {
		httpjson.WriteError(w, http.StatusNotFound, "LEDGER_NOT_FOUND", "The Ledger is missing; run Bootstrap")
		return
	}
	httpjson.WriteError(w, http.StatusBadGateway, "GOOGLE_ERROR", err.Error())
}
